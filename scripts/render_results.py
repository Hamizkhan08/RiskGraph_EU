#!/usr/bin/env python3
"""Render docs/RESULTS.md and artifacts/results_manifest.json from recorded runs.

Every number in RESULTS.md is read from artifacts/runs/<run_id>/*.json — nothing is typed by hand.
results_manifest.json lists every reported figure with its run, dataset, split, feature version,
model, seeds and source file so each can be traced.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "artifacts" / "runs"
ORDER = ["M1_logreg_TB", "M2_lgbm_TB", "M3_lgbm_TBG", "M4_lgbm_TBGM", "A1_lgbm_T", "A2_lgbm_TBG_notype"]


def pct(v: float | None, d: int = 1) -> str:
    return "n/a" if v is None else f"{100 * v:.{d}f} %"


def ci(c) -> str:
    return "n/a" if not c else f"{100 * c[0]:.1f}–{100 * c[1]:.1f} %"


def load(key: str) -> dict:
    d = RUNS / f"Tide-{key}-local-fv1-r1"
    return {n: json.loads((d / f"{n}.json").read_text()) for n in ("manifest", "h1", "h2", "h3", "data_quality")}


def main() -> None:
    data = {k: load(k) for k in ("LI", "HI")}
    out: list[str] = []
    trace: list[dict] = []
    w = out.append

    def rec(ds: str, stage: str, model: str, metric: str, value, view: str = "", seeds: str = "") -> None:
        m = data[ds]["manifest"]
        trace.append(
            {
                "dataset": ds,
                "run_id": m["run_id"],
                "stage": stage,
                "model": model,
                "view": view,
                "metric": metric,
                "value": value,
                "seeds": seeds or m["seeds"],
                "feature_version": m["feature_version"],
                "split": {k: v["dates"] for k, v in m["split"].items() if isinstance(v, dict)},
                "source": f"artifacts/runs/{m['run_id']}/{stage}.json",
            }
        )

    w("# RESULTS\n")
    w("> **Generated by `scripts/render_results.py` from `artifacts/runs/*`. Do not edit by hand.**  ")
    w(
        "> Data: synthetic, generated locally with the MIT-licensed Tide generator at reduced scale (1,500 individuals, 12 months) — "
        "**not** the published Zenodo release. Research prototype; no claim about real-world AML effectiveness.\n"
    )
    for ds in ("LI", "HI"):
        d = data[ds]
        m, h1, h2, h3, dq = d["manifest"], d["h1"], d["h2"], d["h3"], d["data_quality"]
        c = h1["counts"]
        w(f"\n---\n\n## {ds} condition — run `{m['run_id']}`\n")
        w(
            f"* Generated at {m['timestamp_utc']} · pipeline {m['pipeline_version']} · features {m['feature_version']} · seeds {m['seeds']}"
        )
        w(f"* Generator commit `{m['dataset']['generator_commit']}` · config {m['dataset']['config']}")
        w(
            "* Split (dates): "
            + " · ".join(f"{k} {v['dates'][0]}…{v['dates'][1]}" for k, v in m["split"].items() if isinstance(v, dict))
        )
        w(
            f"* Transactions in period {dq['in_period_rows']:,} · positive transactions {dq['positive_transactions']:,} ({100 * dq['positive_prevalence_tx']:.3f} %) · schemes {dq['schemes_total']}"
        )
        w(
            f"* Train cases {c['train_cases']:,} ({c['train_pos']:,} positive) · validation calibration positives {c['val_cal_pos']} · "
            f"test (new-scheme view) {c['test_strict_cases']:,} cases, **{c['test_strict_pos']} positives from {c['test_strict_schemes']} schemes**; all-positives view {c['test_all_pos']} positives\n"
        )
        w("\n### H1 — feature-group ablation (test block, mean ± sd over 3 seeds)\n")
        for view, label in (
            ("strict", "New-scheme view (primary)"),
            ("all", "All positives incl. carry-over (sensitivity)"),
        ):
            w(f"\n**{label}**\n")
            w("| Model | Features | PR-AUC | Recall@K m=1 | Precision@K m=1 | Recall@K m=2 |")
            w("|---|---:|---:|---:|---:|---:|")
            for k in ORDER:
                r = h1["models"][k]["test"][view]
                t1, t2 = r["topk"]["1.0"], r["topk"]["2.0"]
                w(
                    f"| {h1['models'][k]['label']} | {h1['models'][k]['n_features']} | {r['pr_auc']['mean']:.3f} ± {r['pr_auc']['sd']:.3f} | "
                    f"{pct(t1['recall']['mean'])} ± {100 * t1['recall']['sd']:.1f} | {pct(t1['precision']['mean'])} | {pct(t2['recall']['mean'])} |"
                )
                rec(ds, "h1", k, "pr_auc_mean", r["pr_auc"]["mean"], view)
                rec(ds, "h1", k, "recall_at_k_m1_mean", t1["recall"]["mean"], view)
        w(
            "\n**Paired scheme-cluster bootstrap contrasts** (seed 1; recall difference A − B; 500 resamples of schemes)\n"
        )
        w("| A | B | m | Recall A | Recall B | Diff (pp) | 95 % CI (pp) | Schemes |")
        w("|---|---|---:|---:|---:|---:|---:|---:|")
        for x in h1["contrasts"]:
            if x["m"] in (1.0, 2.0):
                w(
                    f"| {x['a']} | {x['b']} | {x['m']} | {pct(x['recall'])} | {pct(x['recall_b'])} | {100 * x['diff']:+.1f} | "
                    f"{100 * x['diff_ci95'][0]:+.1f} … {100 * x['diff_ci95'][1]:+.1f} | {x['n_clusters']} |{' **primary**' if x['primary'] else ''}"
                )
                rec(ds, "h1", f"{x['a']}-{x['b']}", f"recall_diff_m{x['m']}", x["diff"], "strict", "1")
        w("\n**Calibration** (Platt on validation, evaluated on the new-scheme test view)\n")
        w("| Model | Brier ×10⁻³ | Prevalence-only Brier ×10⁻³ | Skill | ECE ×10⁻³ |")
        w("|---|---:|---:|---:|---:|")
        for k in ORDER:
            cal = h1["calibration"][k]
            w(
                f"| {k} | {1000 * cal['brier']:.3f} | {1000 * cal['brier_baseline_prevalence']:.3f} | {pct(1 - cal['brier'] / cal['brier_baseline_prevalence'])} | {1000 * cal['ece']:.3f} |"
            )
            rec(ds, "h1", k, "brier", cal["brier"], "strict", "1")
        w("\n### H2 — leave-one-family-out (m = 1; window from day " + str(h2["window_start_day"]) + ")\n")
        w(
            "| Held-out family | Schemes | Positive cases | M3 seen→held | M3 loss | M4 seen→held | M4 loss | M4−M3 loss (pp, 95 % CI) |"
        )
        w("|---|---:|---:|---|---:|---|---:|---|")
        for f in h2["families"].values():
            b = f["by_m"]["1.0"]
            a3, a4, dd = b["M3_lgbm_TBG"], b["M4_lgbm_TBGM"], b["diff_loss_M4_minus_M3"]
            w(
                f"| {f['family']} | {f['n_schemes']} | {f['n_pos_cases']} | {pct(a3['recall_seen']['mean'], 0)} → {pct(a3['recall_heldout']['mean'], 0)} | {pct(a3['rel_loss']['mean'], 0)} | "
                f"{pct(a4['recall_seen']['mean'], 0)} → {pct(a4['recall_heldout']['mean'], 0)} | {pct(a4['rel_loss']['mean'], 0)} | "
                f"{100 * dd['point']:+.0f} ({100 * dd['ci95'][0]:+.0f} … {100 * dd['ci95'][1]:+.0f}) |"
            )
            rec(ds, "h2", "M3", f"rel_loss_{f['family']}", a3["rel_loss"]["mean"], "post-train window")
            rec(ds, "h2", "M4", f"rel_loss_{f['family']}", a4["rel_loss"]["mean"], "post-train window")
        w("\n### H3 — auto-close policies (same regime, m = 1)\n")
        base = h3["baseline_no_autoclose"]["1.0"]
        w(
            f"Test stream: {h3['stream']['n_cases']:,} cases, {h3['stream']['n_pos']} positives. **No auto-close baseline:** review recall {pct(base['review_recall'])}, "
            f"expired positives {pct(base['expired_positive_rate'])}, mean backlog {base['mean_backlog']:.0f} cases.\n"
        )
        w(
            "| Policy | α | Realised miss | 95 % CI (schemes) | Review recall | Expired positives | Mean backlog | Weeks > α |"
        )
        w("|---|---:|---:|---:|---:|---:|---:|---:|")
        for x in h3["same_regime"]:
            if x["m"] == 1.0:
                p = x["policy"]
                w(
                    f"| {p['kind']} | {pct(p['alpha'], 0)} | {pct(x['realised_miss_rate'])} | {ci(x.get('miss_ci95'))} | {pct(x['review_recall'])} | "
                    f"{pct(x['expired_positive_rate'])} | {x['mean_backlog']:.0f} | {pct(x['violation_rate'], 0) if x['violation_rate'] is not None else 'n/a'} |"
                )
                rec(ds, "h3", p["kind"], f"realised_miss_alpha{p['alpha']}_m1", x["realised_miss_rate"], "strict", "1")
        w("\n**Held-out family (α = 10 %, m = 1)** — model and calibration never saw the family\n")
        w("| Family | Policy | Overall miss | Held-out family miss | Family positives |")
        w("|---|---|---:|---:|---:|")
        for x in h3["heldout"]:
            if x["policy"]["alpha"] == 0.1:
                s = x.get("heldout_family_stats") or {}
                w(
                    f"| {x['heldout_family_name']} | {x['policy']['kind']} | {pct(x['realised_miss_rate'])} | {pct(s.get('miss')) if s else 'no positives'} | {s.get('n_pos', 0)} |"
                )
        w("\n**Labels only for reviewed cases (selection bias; α = 10 %, m = 1)**\n")
        for x in h3["review_only_labels"]:
            w(
                f"* {x['policy']['kind']}: realised miss {pct(x['realised_miss_rate'])} (95 % CI {ci(x.get('miss_ci95'))})"
            )
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n")
    (ROOT / "artifacts" / "results_manifest.json").write_text(
        json.dumps({"n_results": len(trace), "results": trace}, indent=1)
    )
    print(f"wrote docs/RESULTS.md ({len(out)} lines) and results_manifest.json ({len(trace)} traced results)")


if __name__ == "__main__":
    import argparse

    argparse.ArgumentParser(description=__doc__).parse_args()  # so --help does not run the renderer
    main()
